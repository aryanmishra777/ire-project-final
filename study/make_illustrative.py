"""Generate ILLUSTRATIVE (simulated) study data for 15 participants and run the whole study
pipeline on it: pooling, simulated ratings, analysis.

Nothing here comes from a real person. The questions are example questions written for the
demo, the papers are placeholders, and the ratings come from a seeded random model. Every file
written under study/illustrative/ says so. It exists to show the analysis end to end while
the real pilot (study/data/) is pending.
"""
from __future__ import annotations

import csv
import json
import random
from pathlib import Path

from .analyze_study import analyze_study
from .pool import pool_study

OUT = Path(__file__).resolve().parent / "illustrative"
SEED = 7
NOTE = ("ILLUSTRATIVE DATA. Simulated responses generated by study/make_illustrative.py. "
        "Not real participants. Do not report as study results.\n")
QUESTIONS = [  # example questions written for the demo, one per simulated participant
    "How do people make speech recognition work for low-resource Indian languages?",
    "Methods to detect hallucinated facts in summaries generated by language models",
    "Can graph neural networks predict traffic congestion from sparse sensor data?",
    "What evaluation metrics exist for code generated by large language models?",
    "Techniques for 3D reconstruction of indoor scenes from a single RGB image",
    "How to make small language models follow instructions without much labelled data",
    "Approaches to fair ranking in recommender systems for new content creators",
    "Robot grasping of transparent objects using depth sensors",
    "Detecting misinformation in code-mixed Hindi-English social media posts",
    "Energy-efficient scheduling of deep learning jobs on GPU clusters",
    "Using eye tracking to measure cognitive load during programming tasks",
    "Retrieval-augmented generation for answering questions over legal documents",
    "Self-supervised pretraining for medical image segmentation with few labels",
    "How does curriculum learning affect reinforcement learning for navigation?",
    "Query expansion methods for searching scientific literature",
]
FIDELITY = [5, 4, 4, 2, 5, 3, 4, 5, 2, 4, 3, 5, 4, 3, 1]  # simulated Part B ratings


def _paper(pid: str, i: int) -> dict:
    return {"id": f"{pid}-sim{i:02d}", "title": f"Simulated paper {i:02d} ({pid})",
            "abstract": "Placeholder abstract: simulated data, not a real paper.",
            "year": "", "venue": "", "doi": f"sim/{pid}/{i:02d}"}


def simulate_runs(rng: random.Random) -> dict[str, dict[str, int]]:
    """Write runs/<pid>.json; return each participant's hidden 'true' grades by doi."""
    truth = {}
    for n, (q, fid) in enumerate(zip(QUESTIONS, FIDELITY), start=1):
        pid = f"P{n:02d}"
        papers = [_paper(pid, i) for i in range(1, 25)]
        grade = {p["doi"]: rng.choices([2, 1, 0], weights=[25, 30, 45])[0] for p in papers}
        weight_on = 1.0 + 0.3 * (fid - 3)  # better fidelity → the 'on' run ranks better
        off = sorted(papers, key=lambda p: -(grade[p["doi"]] + rng.gauss(0, 1.2)))[:10]
        on = sorted(papers, key=lambda p: -(weight_on * grade[p["doi"]] + rng.gauss(0, 1.2)))[:10]
        run = {"pid": pid, "question": q, "rewrite": "(simulated rewrite)", "on": on, "off": off,
               "note": NOTE.strip()}
        (OUT / "runs" / f"{pid}.json").write_text(json.dumps(run, indent=2), encoding="utf-8")
        truth[pid] = grade
    return truth


def simulate_ratings(rng: random.Random, truth: dict[str, dict[str, int]]) -> None:
    """Fill each rating sheet with the true grade, plus a 10% chance of a ±1 rater slip."""
    (OUT / "ratings").mkdir(exist_ok=True)
    key = {}
    for pid in truth:
        run = json.loads((OUT / "runs" / f"{pid}.json").read_text(encoding="utf-8"))
        for p in run["on"] + run["off"]:
            key[(pid, p["title"])] = truth[pid][p["doi"]]
    for pid in truth:
        with open(OUT / "rating_sheets" / f"{pid}.csv", encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        for r in rows:
            g = key[(pid, r["title"])]
            if rng.random() < 0.10:
                g = min(2, max(0, g + rng.choice([-1, 1])))
            r["grade"] = g
        with open(OUT / "ratings" / f"{pid}.csv", "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)


def simulate_fidelity() -> None:
    with open(OUT / "fidelity_template.csv", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for r, fid in zip(rows, FIDELITY):
        r["fidelity"] = fid
        r["dropped_term"] = "(simulated)" if fid <= 2 else ""
    with open(OUT / "fidelity.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def main() -> None:
    (OUT / "runs").mkdir(parents=True, exist_ok=True)
    (OUT / "ILLUSTRATIVE.txt").write_text(NOTE, encoding="utf-8")
    rng = random.Random(SEED)
    truth = simulate_runs(rng)
    pool_study(OUT)
    simulate_ratings(rng, truth)
    simulate_fidelity()
    print(analyze_study(OUT))


if __name__ == "__main__":
    main()
